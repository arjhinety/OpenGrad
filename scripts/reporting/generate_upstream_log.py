#!/usr/bin/env python3
"""Generate the table and entry sections of ``docs/UPSTREAM_ISSUES.md`` from one file per entry.

Why this exists
---------------
Until 2026-11-11 the log was one hand-written file: a summary table and a section per entry. The table drifted
from the sections (it stopped at UP-0017 while the sections reached UP-0021), and the only record of what could
go upstream was prose. Each entry is now its own file, ``docs/upstream/UP-NNNN.md``. A YAML front matter holds
the fields the table and the checks need, and the body is the entry's text, unchanged. ``docs/UPSTREAM_ISSUES.md``
keeps its hand-written rules; everything between the generated markers is rebuilt from the entry files, so the
table cannot drift from the sections again. ``tests/repo/test_upstream_log.py`` requires the committed file to
match and every entry to pass ``validate``.

Usage:
    python scripts/reporting/generate_upstream_log.py            # rewrite the generated block
    python scripts/reporting/generate_upstream_log.py --check    # fail if it is stale or an entry is invalid
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[2]
LOG = Path("docs/UPSTREAM_ISSUES.md")
ENTRIES = Path("docs/upstream")
BEGIN = "<!-- BEGIN GENERATED by scripts/reporting/generate_upstream_log.py from docs/upstream/; do not edit by hand -->"
END = "<!-- END GENERATED -->"

#: Whose problem it is.
CLASSES = ("OURS", "UPSTREAM", "UNCLEAR", "NOT A BUG", "FEATURE GAP")
#: Where it stands with the upstream project. Filing is a lifecycle, not a class.
STATUSES = ("not-applicable", "not-filed", "candidate", "filed", "merged", "declined")
#: Classes whose problem sits in someone else's code, so they must name it.
EXTERNAL = ("UPSTREAM", "FEATURE GAP")
REQUIRED = ("id", "date", "where", "class", "summary", "state", "upstream")
ID_PATTERN = re.compile(r"UP-\d{4}")
LATER_LINE = re.compile(r"^Later line for (UP-\d{4})\b", re.MULTILINE)


def split_entry(text: str) -> tuple[dict[str, Any], str]:
    """Front matter and body of one entry file."""
    if not text.startswith("---\n"):
        raise ValueError("an entry file starts with a '---' front matter block")
    front, sep, body = text[4:].partition("\n---\n")
    if not sep:
        raise ValueError("the front matter block is not closed with '---'")
    data = yaml.safe_load(front)
    if not isinstance(data, dict):
        raise ValueError("the front matter is not a mapping")  # noqa: TRY004 -- load() reports every bad entry together
    return data, body.strip("\n")


def validate(data: dict[str, Any], body: str, filename: str) -> list[str]:
    """Every problem with one entry; an empty list means it is valid."""
    errors = [f"missing field {key!r}" for key in REQUIRED if key not in data]
    if errors:
        return errors
    entry_id = str(data["id"])
    if not ID_PATTERN.fullmatch(entry_id) or filename != f"{entry_id}.md":
        errors.append(f"id {entry_id!r} must be UP-NNNN and match the file name {filename!r}")
    for key in ("date", "where", "summary", "state"):
        if not isinstance(data[key], str) or not data[key].strip():
            errors.append(f"{key!r} must be a non-empty string")
    if data["class"] not in CLASSES:
        errors.append(f"class {data['class']!r} is not one of {CLASSES}")
    upstream = data["upstream"]
    if not isinstance(upstream, dict) or upstream.get("status") not in STATUSES:
        errors.append(f"upstream.status must be one of {STATUSES}")
        return errors
    status = upstream["status"]
    if status in ("not-applicable", "not-filed") and upstream.get("url"):
        errors.append(f"upstream.url is set, but upstream.status is {status!r}")
    if status in ("filed", "merged", "declined") and not upstream.get("url"):
        errors.append(f"upstream.status {status!r} needs upstream.url (the issue or pull request)")
    if data["class"] in EXTERNAL:
        if status == "not-applicable":
            errors.append(
                f"a {data['class']} entry needs an upstream status other than not-applicable"
            )
        for key in ("library", "version"):
            if not str(data.get(key) or "").strip():
                errors.append(f"a {data['class']} entry names its {key!r}")
        if data["class"] == "FEATURE GAP" and not str(data.get("workaround") or "").strip():
            errors.append("a FEATURE GAP entry names its 'workaround' (the file or mechanism)")
    if status in ("candidate", "filed", "merged", "declined"):
        # Ready to go upstream only with the evidence the rules ask for.
        for key in ("reproduction", "tracker_search"):
            if not str(upstream.get(key) or "").strip():
                errors.append(f"upstream.status {status!r} needs upstream.{key}")
    heading = body.split("\n", 1)[0]
    if not heading.startswith(f"## {entry_id} — ") or f"(`{data['class']}`" not in heading:
        errors.append(
            f"the body starts with the heading '## {entry_id} — <title> (`{data['class']}`...)'"
        )
    for other in LATER_LINE.findall(body):
        if other != entry_id:
            errors.append(f"a later line for {other} belongs at the end of {other}.md, not here")
    return errors


def load(root: Path = ROOT) -> list[tuple[dict[str, Any], str]]:
    entries = []
    problems = []
    for path in sorted((root / ENTRIES).glob("UP-*.md")):
        try:
            data, body = split_entry(path.read_text(encoding="utf-8"))
        except ValueError as exc:
            problems.append(f"{path.name}: {exc}")
            continue
        problems += [f"{path.name}: {error}" for error in validate(data, body, path.name)]
        entries.append((data, body))
    ids = [str(data.get("id")) for data, _ in entries]
    expected = [f"UP-{n:04d}" for n in range(1, len(ids) + 1)]
    if ids != expected:
        problems.append(f"entry ids must run UP-0001..UP-{len(ids):04d} without gaps; found {ids}")
    if problems:
        raise ValueError("invalid upstream log entries:\n" + "\n".join(problems))
    return entries


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def render_block(entries: list[tuple[dict[str, Any], str]]) -> str:
    lines = [
        BEGIN,
        "",
        "| ID | Date | Where | Class | Upstream | Summary | State |",
        "|---|---|---|---|---|---|---|",
    ]
    for data, _ in entries:
        klass = f"`{data['class']}`" + (f" {data['class_note']}" if data.get("class_note") else "")
        upstream = data["upstream"]["status"]
        if data["upstream"].get("url"):
            upstream = f"[{upstream}]({data['upstream']['url']})"
        cells = [
            data["id"],
            data["date"],
            data["where"],
            klass,
            upstream,
            data["summary"],
            data["state"],
        ]
        lines.append("| " + " | ".join(_cell(str(cell)) for cell in cells) + " |")
    lines += ["", "---", ""]
    for _, body in entries:
        lines += [body, ""]
    lines.append(END)
    # No newline after END: whatever followed the marker in the file is kept exactly as it was.
    return "\n".join(lines)


def render(root: Path = ROOT) -> str:
    text = (root / LOG).read_text(encoding="utf-8")
    head, sep, rest = text.partition(BEGIN)
    if not sep or END not in rest:
        raise ValueError(f"{LOG} lacks the generated markers")
    tail = rest.split(END, 1)[1]
    return head + render_block(load(root)) + tail


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").split("\n\n")[0])
    parser.add_argument(
        "--check", action="store_true", help="fail if the log is stale or an entry is invalid"
    )
    args = parser.parse_args(argv)
    try:
        new = render()
    except ValueError as exc:
        print(f"FAIL: {exc}")
        return 1
    path = ROOT / LOG
    if args.check:
        if path.read_text(encoding="utf-8") != new:
            print(f"FAIL: {LOG} is stale: run python scripts/reporting/generate_upstream_log.py")
            return 1
        print(f"{LOG} is current")
        return 0
    path.write_text(new, encoding="utf-8", newline="\n")
    print(f"wrote {LOG}")
    return 0


if __name__ == "__main__":
    from opengrad.runrecords.scripts import run_script

    raise SystemExit(run_script(__file__, main))
